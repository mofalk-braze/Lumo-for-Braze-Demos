const GENERATED_HEADER = '# Generated by demo launcher.'

export function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

export function readProperties(file) {
  if (!fs.existsSync(file)) return {}
  const result = {}
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const equals = trimmed.indexOf('=')
    if (equals < 0) continue
    result[trimmed.slice(0, equals).trim()] = trimmed.slice(equals + 1).trim()
  }
  return result
}

function restEnvKeyName(packId) {
  const suffix = String(packId || '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
  return suffix ? `BRAZE_REST_API_KEY_${suffix}` : ''
}

function hasHostRestKey(packId, secrets = {}) {
  const packEnv = restEnvKeyName(packId)
  return Boolean(
    (packEnv && process.env[packEnv]) ||
      process.env.BRAZE_REST_API_KEY ||
      (process.env.BRAZE_CONTROL_ROOM_ALLOW_LEGACY_REST_KEY === '1' && secrets['braze.restApiKey'])
  )
}

export function resolvePackPath(pack, value, { fallback = '' } = {}) {
  const raw = value || fallback
  if (!raw) return ''
  return path.isAbsolute(raw) ? raw : path.resolve(repoRoot, raw)
}

export function packWebDistDir(pack) {
  return resolvePackPath(pack, pack.web?.distDir, { fallback: path.join(webTemplateDir, 'dist') })
}

export function packWebBuildCommand(pack) {
  if (pack.web?.build === false) return null
  if (pack.web?.build?.command) {
    return {
      command: pack.web.build.command,
      args: Array.isArray(pack.web.build.args) ? pack.web.build.args : [],
      cwd: resolvePackPath(pack, pack.web.build.cwd, {
        fallback: pack.web?.sourceDir || pack.directory || repoRoot,
      }),
    }
  }
  if (pack.web?.distDir) return null
  return { command: 'npm', args: ['run', 'build'], cwd: webTemplateDir }
}

export function writeProperties(file, values, comments = []) {
  const body = [
    GENERATED_HEADER,
    ...comments.map((line) => `# ${line}`),
    '',
    ...Object.entries(values).map(([key, value]) => `${key}=${value ?? ''}`),
    '',
  ].join('\n')
  fs.writeFileSync(file, body)
}

export function listDemoPacks() {
  const roots = [
    { dir: demoPacksDir, source: 'committed', sourceLabel: 'Committed pack' },
    { dir: localDemoPacksDir, source: 'local', sourceLabel: 'Local workspace pack' },
  ]
  return roots
    .flatMap((root) => {
      if (!fs.existsSync(root.dir)) return []
      return fs
        .readdirSync(root.dir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => ({ ...root, entry }))
    })
    .map(({ dir: rootDir, source, sourceLabel, entry }) => {
      const dir = path.join(rootDir, entry.name)
      const configPath = path.join(dir, 'demo-pack.json')
      if (!fs.existsSync(configPath)) return null
      const pack = validatePack(readJson(configPath), configPath)
      const secretsPath = path.join(dir, 'secrets.properties')
      const secrets = readProperties(secretsPath)
      return {
        ...pack,
        directory: dir,
        source,
        sourceLabel,
        hasSecrets: fs.existsSync(secretsPath),
        restConfigured: Boolean(secrets['braze.restEndpoint'] && hasHostRestKey(pack.id, secrets)),
      }
    })
    .filter(Boolean)
    .sort((a, b) => {
      if (a.id === 'lumo-default') return -1
      if (b.id === 'lumo-default') return 1
      return a.name.localeCompare(b.name)
    })
}

function findDemoPackDirectory(packId) {
  const roots = [demoPacksDir, localDemoPacksDir]

  for (const root of roots) {
    const directDir = path.join(root, packId)
    if (fs.existsSync(path.join(directDir, 'demo-pack.json'))) {
      return directDir
    }
  }

  for (const root of roots) {
    if (!fs.existsSync(root)) continue
    for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const dir = path.join(root, entry.name)
      const configPath = path.join(dir, 'demo-pack.json')
      if (!fs.existsSync(configPath)) continue
      const pack = validatePack(readJson(configPath), configPath)
      if (pack.id === packId || entry.name === packId) return dir
    }
  }

  return null
}

export function getDemoPack(packId) {
  const packDir = findDemoPackDirectory(packId)
  if (!packDir) {
    throw new Error(`Demo pack not found: ${packId}`)
  }
  const configPath = path.join(packDir, 'demo-pack.json')
  const isLocal = packDir.startsWith(`${localDemoPacksDir}${path.sep}`)
  return {
    ...validatePack(readJson(configPath), configPath),
    directory: packDir,
    source: isLocal ? 'local' : 'committed',
    sourceLabel: isLocal ? 'Local workspace pack' : 'Committed pack',
    secrets: readProperties(path.join(packDir, 'secrets.properties')),
  }
}

export function demoPackSecretsPath(packOrId) {
  const pack = typeof packOrId === 'string' ? getDemoPack(packOrId) : packOrId
  return path.join(pack.directory, 'secrets.properties')
}

export function writeDemoPackSecrets(packOrId, values, comments = []) {
  const pack = typeof packOrId === 'string' ? getDemoPack(packOrId) : packOrId
  const file = demoPackSecretsPath(pack)
  const current = readProperties(file)
  const next = { ...current }
  for (const [key, value] of Object.entries(values || {})) {
    if (value === undefined || value === null) continue
    const stringValue = String(value)
    if (!stringValue && current[key]) continue
    next[key] = stringValue
  }
  writeProperties(file, next, comments.length ? comments : [
    `Local credentials for ${pack.name} (${pack.id})`,
    'Generated by the Demo Control Room. Do not commit this file.',
  ])
  return readProperties(file)
}

export function getActivePackId() {
  if (fs.existsSync(activePackMarkerPath)) {
    const id = fs.readFileSync(activePackMarkerPath, 'utf8').trim()
    if (id && findDemoPackDirectory(id)) return id
  }
  if (findDemoPackDirectory('lumo-default')) return 'lumo-default'
  return listDemoPacks()[0]?.id || ''
}

export function ensureActiveWebConfig() {
  const pack = getDemoPack(getActivePackId())
  if (fs.existsSync(generatedConfigPath) && fs.existsSync(generatedRuntimeManifestPath)) return
  syncDemoAssets(pack)
  cleanLegacyAndroidGeneratedAssets()
  const manifest = generateRuntimeManifest(pack)
  generateWebConfig(pack, manifest)
}

export function applyDemoPack(packId, { writeAndroid = true, launcherCallbackUrl = '', iosLauncherCallbackUrl = '' } = {}) {
  const pack = getDemoPack(packId)
  syncDemoAssets(pack)
  cleanLegacyAndroidGeneratedAssets()
  const manifest = generateRuntimeManifest(pack)
  generateWebConfig(pack, manifest)
  fs.writeFileSync(activePackMarkerPath, `${pack.id}\n`)
  if (writeAndroid) writeAndroidSeedConfig(pack, manifest, { launcherCallbackUrl })
  writeIosRuntimeDefaults(pack, manifest, { launcherCallbackUrl: iosLauncherCallbackUrl })
  return { ...pack, runtimeManifest: manifest }
}

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true })
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name)
    const to = path.join(dest, entry.name)
    if (entry.isDirectory()) copyDir(from, to)
    else if (entry.isFile()) fs.copyFileSync(from, to)
  }
}

function syncDemoAssets(pack) {
  const source = path.join(pack.directory, 'assets')
  const dest = path.join(generatedDemoAssetsDir, pack.id)
  fs.rmSync(dest, { recursive: true, force: true })
  if (fs.existsSync(source)) copyDir(source, dest)
}

function cleanLegacyAndroidGeneratedAssets() {
  fs.rmSync(path.join(androidShellDir, 'app/build/generated/assets/lumoWeb'), { recursive: true, force: true })
}

function validatePack(pack, file) {
  const required = ['id', 'name', 'brand', 'content']
  for (const key of required) {
    if (!pack[key]) throw new Error(`${file} is missing required field: ${key}`)
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(pack.id)) {
    throw new Error(`${file} id must be kebab-case: ${pack.id}`)
  }
  if (!pack.brand.colors || !Array.isArray(pack.brand.tabs) || !pack.brand.demoUser) {
    throw new Error(`${file} has an incomplete brand section`)
  }
  if (!pack.content.hero || !Array.isArray(pack.content.categories) || !Array.isArray(pack.content.rails)) {
    throw new Error(`${file} has an incomplete content section`)
  }
  validateContentCardSurfaces(pack, file)
  if (pack.launcher?.presets && !Array.isArray(pack.launcher.presets)) {
    throw new Error(`${file} launcher.presets must be an array`)
  }
  if (pack.web?.distDir && typeof pack.web.distDir !== 'string') {
    throw new Error(`${file} web.distDir must be a string`)
  }
  if (pack.web?.build && typeof pack.web.build !== 'object') {
    throw new Error(`${file} web.build must be an object or false`)
  }
  if (pack.web?.build?.command && typeof pack.web.build.command !== 'string') {
    throw new Error(`${file} web.build.command must be a string`)
  }
  return pack
}

function validateContentCardSurfaces(pack, file) {
  const surfaces = pack.content?.contentCardSurfaces
  if (surfaces === undefined) return
  if (!Array.isArray(surfaces)) {
    throw new Error(`${file} content.contentCardSurfaces must be an array`)
  }
  const allowedSurfaces = new Set(['inbox', 'feed', 'carousel', 'hero', 'account', 'status'])
  const allowedVariants = new Set(['hero', 'carousel', 'feed', 'inbox'])
  const allowedEmpty = new Set(['hide', 'empty-state'])
  for (const [index, surface] of surfaces.entries()) {
    const prefix = `${file} content.contentCardSurfaces[${index}]`
    for (const key of ['id', 'placement', 'surface', 'screen', 'title', 'variant', 'emptyBehavior']) {
      if (typeof surface?.[key] !== 'string' || !surface[key]) {
        throw new Error(`${prefix} is missing required string field: ${key}`)
      }
    }
    if (!allowedSurfaces.has(surface.surface)) throw new Error(`${prefix} has unsupported surface: ${surface.surface}`)
    if (!allowedVariants.has(surface.variant)) throw new Error(`${prefix} has unsupported variant: ${surface.variant}`)
    if (!allowedEmpty.has(surface.emptyBehavior)) {
      throw new Error(`${prefix} has unsupported emptyBehavior: ${surface.emptyBehavior}`)
    }
    if (surface.maxCards !== undefined && (!Number.isInteger(surface.maxCards) || surface.maxCards < 1)) {
      throw new Error(`${prefix} maxCards must be a positive integer`)
    }
  }
}

export function demoConfigHash(pack) {
  const publicPack = {
    id: pack.id,
    name: pack.name,
    description: pack.description || '',
    android: pack.android || null,
    ios: pack.ios || null,
    brand: pack.brand,
    content: pack.content,
    launcher: pack.launcher || null,
    web: pack.web || null,
  }
  return createHash('sha256')
    .update(JSON.stringify(publicPack))
    .digest('hex')
    .slice(0, 16)
}

export function createRuntimeManifest(pack) {
  const hash = demoConfigHash(pack)
  return {
    schemaVersion: 1,
    id: pack.id,
    name: pack.name,
    description: pack.description || '',
    externalId: pack.android?.defaultExternalId || pack.brand.demoUser.externalId,
    configHash: hash,
    generatedAt: new Date().toISOString(),
    assetBase: `/demo-assets/${pack.id}`,
    sourceMode: pack.web?.distDir ? 'external-web-dist' : 'generated-demo-pack',
    webDistDir: pack.web?.distDir ? packWebDistDir(pack) : '',
    expectedSources: {
      browser: 'http://localhost:5173',
      android: 'file:///android_asset/demo/index.html',
      ios: 'http://localhost:5173',
    },
  }
}

export function generateRuntimeManifest(pack) {
  const manifest = createRuntimeManifest(pack)
  fs.mkdirSync(path.dirname(generatedRuntimeManifestPath), { recursive: true })
  fs.writeFileSync(generatedRuntimeManifestPath, `${JSON.stringify(manifest, null, 2)}\n`)
  return manifest
}

function generateWebConfig(pack, manifest) {
  fs.mkdirSync(path.dirname(generatedConfigPath), { recursive: true })
  const source = `// Generated by tools/demo-launcher.mjs. Do not edit by hand.
import type { BrandConfig } from './brandConfig'
import type { AppContent } from './content'

export const activeDemoPackId: string = ${JSON.stringify(pack.id)}
export const activeBrandConfig: BrandConfig = ${JSON.stringify(pack.brand, null, 2)}
export const activeAppContent: AppContent = ${JSON.stringify(pack.content, null, 2)}
export const activeRuntimeManifest = ${JSON.stringify(manifest, null, 2)} as const
`
  fs.writeFileSync(generatedConfigPath, source)
}

function writeAndroidSeedConfig(pack, manifest, { launcherCallbackUrl = '' } = {}) {
  const existing = readProperties(androidLocalPropertiesPath)
  const secrets = pack.secrets ?? {}
  const android = pack.android ?? {}
  const sdkDir = secrets['sdk.dir'] || existing['sdk.dir'] || `${process.env.HOME}/Library/Android/sdk`
  const profileName = secrets['demo.profileName'] || android.defaultProfileName || pack.name
  const externalId = secrets['demo.externalId'] || android.defaultExternalId || pack.brand.demoUser.externalId
  const values = {
    'sdk.dir': sdkDir,
    'braze.apiKey': secrets['braze.apiKey'] || existing['braze.apiKey'] || '',
    'braze.endpoint': secrets['braze.endpoint'] || existing['braze.endpoint'] || '',
    'firebase.senderId': secrets['firebase.senderId'] || existing['firebase.senderId'] || '',
    'demo.packId': manifest.id,
    'demo.packName': manifest.name,
    'demo.configHash': manifest.configHash,
    'demo.generatedAt': manifest.generatedAt,
    'demo.sourceMode': 'bundled-asset',
    'demo.browserUrl': manifest.expectedSources.browser,
    'demo.androidUrl': manifest.expectedSources.android,
    'demo.iosUrl': manifest.expectedSources.ios,
    'demo.webDist': packWebDistDir(pack),
    'demo.externalId': externalId,
    'demo.profileName': profileName,
    'launcher.callbackUrl': launcherCallbackUrl || existing['launcher.callbackUrl'] || '',
  }

  if (fs.existsSync(androidLocalPropertiesPath)) {
    const current = fs.readFileSync(androidLocalPropertiesPath, 'utf8')
    if (!current.startsWith(GENERATED_HEADER)) {
      const backup = `${androidLocalPropertiesPath}.backup.${new Date().toISOString().replace(/[-:T.Z]/g, '').slice(0, 14)}`
      fs.copyFileSync(androidLocalPropertiesPath, backup)
    }
  }

  writeProperties(androidLocalPropertiesPath, values, [
    `Active demo pack: ${pack.name} (${pack.id})`,
    'Secrets are local-only; do not commit this file.',
  ])
}

function swiftStringLiteral(value) {
  return `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function upsertSwiftLet(source, name, value) {
  const line = `  static let ${name} = ${swiftStringLiteral(value)}`
  const pattern = new RegExp(`^\\s*static let ${name} = .*$`, 'm')
  if (pattern.test(source)) return source.replace(pattern, line)
  return source.replace(/\n}\s*$/, `\n${line}\n}`)
}

function upsertSwiftUrlLet(source, name, value) {
  const line = `  static let ${name} = URL(string: ${swiftStringLiteral(value)})!`
  const pattern = new RegExp(`^\\s*static let ${name} = URL\\(string: .*$`, 'm')
  if (pattern.test(source)) return source.replace(pattern, line)
  return source.replace(/\n}\s*$/, `\n${line}\n}`)
}

function writeIosRuntimeDefaults(pack, manifest, { launcherCallbackUrl = '' } = {}) {
  if (!fs.existsSync(iosConfigPath)) return
  const secrets = pack.secrets ?? {}
  let source = fs.readFileSync(iosConfigPath, 'utf8')
  source = upsertSwiftLet(source, 'brazeAPIKey', secrets['braze.apiKey'] || '')
  source = upsertSwiftLet(source, 'brazeEndpoint', secrets['braze.endpoint'] || '')
  source = upsertSwiftUrlLet(source, 'webURL', manifest.expectedSources.ios)
  source = upsertSwiftLet(source, 'demoPackId', manifest.id)
  source = upsertSwiftLet(source, 'demoPackName', manifest.name)
  source = upsertSwiftLet(source, 'demoExternalId', secrets['demo.externalId'] || manifest.externalId)
  source = upsertSwiftLet(source, 'demoConfigHash', manifest.configHash)
  source = upsertSwiftLet(source, 'demoGeneratedAt', manifest.generatedAt)
  source = upsertSwiftLet(source, 'demoSourceMode', 'vite-dev-server')
  source = upsertSwiftLet(source, 'browserWebURL', manifest.expectedSources.browser)
  source = upsertSwiftLet(source, 'androidWebURL', manifest.expectedSources.android)
  source = upsertSwiftLet(source, 'iosWebURL', manifest.expectedSources.ios)
  source = upsertSwiftLet(source, 'launcherCallbackUrl', launcherCallbackUrl)
  source = source.replace(/http:\/\/localhost:5174/g, manifest.expectedSources.ios)
  fs.writeFileSync(iosConfigPath, source)
}
