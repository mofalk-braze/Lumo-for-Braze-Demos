function packDestination(destinationRoot, id) {
  const packId = assertDemoPackId(id)
  const root = path.resolve(destinationRoot)
  const destination = path.resolve(root, packId)
  if (path.dirname(destination) !== root) throw new Error(`Unsafe demo pack destination: ${destination}`)
  return destination
}

function duplicateIdsFor(id, knownPacks) {
  return knownPacks.filter((pack) => pack.id === id)
}

function assertPackDestinationAvailable(id, destinationRoot, knownPacks) {
  const destination = packDestination(destinationRoot, id)
  if (fs.existsSync(destination)) throw new Error(`Demo pack directory already exists: ${destination}`)
  if (duplicateIdsFor(id, knownPacks).length) throw new Error(`Demo pack id already exists: ${id}`)
  return destination
}

function knownPacksForDestination(destinationRoot, knownPacks) {
  if (Array.isArray(knownPacks)) return knownPacks
  if (path.resolve(destinationRoot) === path.resolve(localDemoPacksDir)) return listDemoPacks()
  return []
}

function isCredentialLikePackPath(relative) {
  const basename = path.basename(relative)
  if (PACK_COPY_EXCLUDED_BASENAMES.has(basename)) return true
  if (basename === '.env' || basename.startsWith('.env.')) return true
  if (/firebase.*(?:admin|service)|service[-_]?account|credentials?|private[-_]?key|braze[-_]?secrets/i.test(basename)) return true
  return PACK_COPY_EXCLUDED_EXTENSIONS.has(path.extname(basename).toLowerCase())
}

function copyPackTree(source, destination, prefix = '') {
  fs.mkdirSync(destination, { recursive: true })
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name
    if (!isPortableAssetEntry(entry.name) || isCredentialLikePackPath(relative) || relative === 'notes.md') continue
    const from = path.join(source, entry.name)
    const to = path.join(destination, entry.name)
    if (entry.isDirectory()) copyPackTree(from, to, relative)
    else if (entry.isFile()) fs.copyFileSync(from, to)
  }
}

function updateDuplicatedPackIdentity(pack, { id, name, description }) {
  const next = structuredClone(pack)
  delete next.directory
  delete next.source
  delete next.sourceLabel
  delete next.secrets
  delete next.hasSecrets
  delete next.restConfigured
  next.id = id
  next.name = name
  next.description = description || `Local duplicate of ${pack.name}.`
  const externalId = `${id}-demo-user`
  next.brand = {
    ...next.brand,
    appName: name,
    displayName: name,
    demoUser: {
      ...next.brand.demoUser,
      externalId,
      firstName: name.split(/\s+/)[0],
    },
  }
  next.android = {
    ...(next.android || {}),
    defaultExternalId: externalId,
    defaultProfileName: name,
  }
  return next
}

function updatePackAppSurfaceIdentity(directory, sourceId, targetId) {
  const adapter = path.join(directory, 'app-source/web-template/src/screens/local-pack/pack-app.tsx')
  if (!fs.existsSync(adapter)) return false
  const source = fs.readFileSync(adapter, 'utf8')
  const escapedSourceId = sourceId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const pattern = new RegExp(`(export\\s+const\\s+demoPackId(?:\\s*:\\s*string)?\\s*=\\s*)(['"])${escapedSourceId}\\2`)
  const next = source.replace(pattern, (_, declaration) => `${declaration}${JSON.stringify(targetId)}`)
  if (next === source) return false
  fs.writeFileSync(adapter, next)
  return true
}

export function ensureDemoPackNotes(packOrId, { overwrite = false } = {}) {
  const pack = typeof packOrId === 'string' ? getDemoPack(packOrId) : packOrId
  const notesPath = path.join(pack.directory, 'notes.md')
  if (!overwrite && fs.existsSync(notesPath)) return { path: notesPath, changed: false }
  return { path: notesPath, changed: writeTextIfChanged(notesPath, generateDemoPackNotes(pack)) }
}

export function createDemoPack(
  { id, name, description = '' },
  { destinationRoot = localDemoPacksDir, knownPacks } = {},
) {
  const pack = createStarterDemoPackConfig({ id, name, description })
  const destination = assertPackDestinationAvailable(
    pack.id,
    destinationRoot,
    knownPacksForDestination(destinationRoot, knownPacks),
  )
  fs.mkdirSync(destination, { recursive: true })
  try {
    const configPath = path.join(destination, 'demo-pack.json')
    writeTextIfChanged(configPath, `${JSON.stringify(pack, null, 2)}\n`)
    fs.mkdirSync(path.join(destination, 'assets'), { recursive: true })
    const result = {
      ...validatePack(readJson(configPath), configPath),
      directory: destination,
      source: 'local',
      sourceLabel: 'Local workspace pack',
    }
    ensureDemoPackNotes(result, { overwrite: true })
    return result
  } catch (error) {
    fs.rmSync(destination, { recursive: true, force: true })
    throw error
  }
}

export function duplicateDemoPack(
  sourcePackOrId,
  { id, name = '', description = '', destinationRoot = localDemoPacksDir, knownPacks } = {},
) {
  const sourcePack = typeof sourcePackOrId === 'string' ? getDemoPack(sourcePackOrId) : sourcePackOrId
  const targetId = assertDemoPackId(id)
  const targetName = String(name || '').trim() || `${sourcePack.name} Copy`
  const destination = assertPackDestinationAvailable(
    targetId,
    destinationRoot,
    knownPacksForDestination(destinationRoot, knownPacks),
  )
  fs.mkdirSync(destination, { recursive: true })
  try {
    copyPackTree(sourcePack.directory, destination)
    const configPath = path.join(destination, 'demo-pack.json')
    const next = updateDuplicatedPackIdentity(sourcePack, {
      id: targetId,
      name: targetName,
      description: String(description || '').trim(),
    })
    writeTextIfChanged(configPath, `${JSON.stringify(next, null, 2)}\n`)
    updatePackAppSurfaceIdentity(destination, sourcePack.id, targetId)
    const result = {
      ...validatePack(readJson(configPath), configPath),
      directory: destination,
      source: 'local',
      sourceLabel: 'Local workspace pack',
    }
    ensureDemoPackNotes(result, { overwrite: true })
    return result
  } catch (error) {
    fs.rmSync(destination, { recursive: true, force: true })
    throw error
  }
}

export function validateDemoPackForAuthoring(packOrId, { knownPacks } = {}) {
  const pack = typeof packOrId === 'string' ? getDemoPack(packOrId) : packOrId
  const configPath = path.join(pack.directory || '.', 'demo-pack.json')
  validatePack(pack, configPath)
  const packs = Array.isArray(knownPacks) ? knownPacks : listDemoPacks()
  const errors = []
  const warnings = []
  if (!pack.description) errors.push('description is required for runtime validation')
  if (duplicateIdsFor(pack.id, packs).length > 1) errors.push(`duplicate demo pack id: ${pack.id}`)
  const notesPath = path.join(pack.directory || '', 'notes.md')
  if (!pack.directory || !fs.existsSync(notesPath)) warnings.push('notes.md handoff is missing')
  return {
    valid: errors.length === 0,
    id: pack.id,
    name: pack.name,
    directory: pack.directory || '',
    source: pack.source || '',
    configHash: demoConfigHash(pack),
    runtimeHash: demoRuntimeHash(pack),
    notesPath: pack.directory && fs.existsSync(notesPath) ? notesPath : '',
    errors,
    warnings,
  }
}

export function listDemoPacks() {
  const roots = [
    { dir: demoPacksDir, source: 'committed', sourceLabel: 'Committed pack' },
    { dir: localDemoPacksDir, source: 'local', sourceLabel: 'Local workspace pack' },
  ]
  return roots
    .flatMap((root) => {
      if (!fs.existsSync(root.dir)) return []
      return fs
        .readdirSync(root.dir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => ({ ...root, entry }))
    })
    .map(({ dir: rootDir, source, sourceLabel, entry }) => {
      const dir = path.join(rootDir, entry.name)
      const configPath = path.join(dir, 'demo-pack.json')
      if (!fs.existsSync(configPath)) return null
      const pack = validatePack(readJson(configPath), configPath)
      const secretsPath = path.join(dir, 'secrets.properties')
      const secrets = readProperties(secretsPath)
      return {
        ...pack,
        directory: dir,
        source,
        sourceLabel,
        hasSecrets: fs.existsSync(secretsPath),
        restConfigured: Boolean(secrets['braze.restEndpoint'] && hasHostRestKey(pack.id, secrets)),
      }
    })
    .filter(Boolean)
    .sort((a, b) => {
      if (a.id === 'lumo-default') return -1
      if (b.id === 'lumo-default') return 1
      return a.name.localeCompare(b.name)
    })
}

function findDemoPackDirectory(packId) {
  const roots = [demoPacksDir, localDemoPacksDir]

  for (const root of roots) {
    const directDir = path.join(root, packId)
    if (fs.existsSync(path.join(directDir, 'demo-pack.json'))) {
      return directDir
    }
  }

  for (const root of roots) {
    if (!fs.existsSync(root)) continue
    for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const dir = path.join(root, entry.name)
      const configPath = path.join(dir, 'demo-pack.json')
      if (!fs.existsSync(configPath)) continue
      const pack = validatePack(readJson(configPath), configPath)
      if (pack.id === packId || entry.name === packId) return dir
    }
  }

  return null
}

export function getDemoPack(packId) {
  const packDir = findDemoPackDirectory(packId)
  if (!packDir) {
    throw new Error(`Demo pack not found: ${packId}`)
  }
  const configPath = path.join(packDir, 'demo-pack.json')
  const isLocal = packDir.startsWith(`${localDemoPacksDir}${path.sep}`)
  return {
    ...validatePack(readJson(configPath), configPath),
    directory: packDir,
    source: isLocal ? 'local' : 'committed',
    sourceLabel: isLocal ? 'Local workspace pack' : 'Committed pack',
    secrets: readProperties(path.join(packDir, 'secrets.properties')),
  }
}

export function demoPackSecretsPath(packOrId) {
  const pack = typeof packOrId === 'string' ? getDemoPack(packOrId) : packOrId
  return path.join(pack.directory, 'secrets.properties')
}

export function writeDemoPackSecrets(packOrId, values, comments = []) {
  const pack = typeof packOrId === 'string' ? getDemoPack(packOrId) : packOrId
  const file = demoPackSecretsPath(pack)
  const current = readProperties(file)
  const next = { ...current }
  for (const [key, value] of Object.entries(values || {})) {
    if (value === undefined || value === null) continue
    const stringValue = String(value)
    if (!stringValue && current[key]) continue
    next[key] = stringValue
  }
  writeProperties(file, next, comments.length ? comments : [
    `Local credentials for ${pack.name} (${pack.id})`,
    'Generated by the Demo Control Room. Do not commit this file.',
  ])
  return readProperties(file)
}

export function getActivePackId() {
  if (fs.existsSync(activePackMarkerPath)) {
    const id = fs.readFileSync(activePackMarkerPath, 'utf8').trim()
    if (id && findDemoPackDirectory(id)) return id
  }
  if (findDemoPackDirectory('lumo-default')) return 'lumo-default'
  return listDemoPacks()[0]?.id || ''
}

