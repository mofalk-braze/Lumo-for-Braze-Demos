export function validatePack(pack, file) {
  const required = ['id', 'name', 'brand', 'content']
  for (const key of required) {
    if (!pack[key]) throw new Error(`${file} is missing required field: ${key}`)
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(pack.id)) {
    throw new Error(`${file} id must be kebab-case: ${pack.id}`)
  }
  if (!pack.brand.colors || !Array.isArray(pack.brand.tabs) || !pack.brand.demoUser) {
    throw new Error(`${file} has an incomplete brand section`)
  }
  if (!pack.content.hero || !Array.isArray(pack.content.categories) || !Array.isArray(pack.content.rails)) {
    throw new Error(`${file} has an incomplete content section`)
  }
  if (
    typeof pack.content.contentCardRail?.title !== 'string' ||
    !pack.content.contentCardRail.title.trim() ||
    typeof pack.content.contentCardRail?.placement !== 'string' ||
    !pack.content.contentCardRail.placement.trim()
  ) {
    throw new Error(`${file} content.contentCardRail requires non-empty title and placement strings`)
  }
  if (
    pack.android?.sessionTimeoutSeconds !== undefined &&
    (!Number.isInteger(pack.android.sessionTimeoutSeconds) || pack.android.sessionTimeoutSeconds < 1)
  ) {
    throw new Error(`${file} android.sessionTimeoutSeconds must be an integer of at least 1`)
  }
  if (
    pack.ios?.sessionTimeoutSeconds !== undefined &&
    (!Number.isInteger(pack.ios.sessionTimeoutSeconds) || pack.ios.sessionTimeoutSeconds < 1)
  ) {
    throw new Error(`${file} ios.sessionTimeoutSeconds must be an integer of at least 1`)
  }
  validateContentCardSurfaces(pack, file)
  validateBannerSurfaces(pack, file)
  if (pack.launcher?.presets && !Array.isArray(pack.launcher.presets)) {
    throw new Error(`${file} launcher.presets must be an array`)
  }
  if (pack.web?.distDir && typeof pack.web.distDir !== 'string') {
    throw new Error(`${file} web.distDir must be a string`)
  }
  if (pack.web?.build && typeof pack.web.build !== 'object') {
    throw new Error(`${file} web.build must be an object or false`)
  }
  if (pack.web?.build?.command && typeof pack.web.build.command !== 'string') {
    throw new Error(`${file} web.build.command must be a string`)
  }
  return pack
}

function validateContentCardSurfaces(pack, file) {
  const surfaces = pack.content?.contentCardSurfaces
  if (surfaces === undefined) return
  if (!Array.isArray(surfaces)) {
    throw new Error(`${file} content.contentCardSurfaces must be an array`)
  }
  const allowedSurfaces = new Set(['inbox', 'feed', 'carousel', 'hero', 'account', 'status'])
  const allowedVariants = new Set(['hero', 'carousel', 'feed', 'inbox'])
  const allowedEmpty = new Set(['hide', 'empty-state'])
  const ids = new Set()
  for (const [index, surface] of surfaces.entries()) {
    const prefix = `${file} content.contentCardSurfaces[${index}]`
    for (const key of ['id', 'placement', 'surface', 'screen', 'title', 'variant', 'emptyBehavior']) {
      if (typeof surface?.[key] !== 'string' || !surface[key].trim()) {
        throw new Error(`${prefix} is missing required string field: ${key}`)
      }
    }
    if (!allowedSurfaces.has(surface.surface)) throw new Error(`${prefix} has unsupported surface: ${surface.surface}`)
    if (!allowedVariants.has(surface.variant)) throw new Error(`${prefix} has unsupported variant: ${surface.variant}`)
    if (!allowedEmpty.has(surface.emptyBehavior)) {
      throw new Error(`${prefix} has unsupported emptyBehavior: ${surface.emptyBehavior}`)
    }
    if (ids.has(surface.id)) throw new Error(`${prefix} has duplicate id: ${surface.id}`)
    ids.add(surface.id)
    if (surface.maxCards !== undefined && (!Number.isInteger(surface.maxCards) || surface.maxCards < 1)) {
      throw new Error(`${prefix} maxCards must be a positive integer`)
    }
  }
}

function validateBannerSurfaces(pack, file) {
  const surfaces = pack.content?.bannerSurfaces
  if (surfaces === undefined) return
  if (!Array.isArray(surfaces)) {
    throw new Error(`${file} content.bannerSurfaces must be an array`)
  }
  const ids = new Set()
  const placements = new Set()
  for (const [index, surface] of surfaces.entries()) {
    const prefix = `${file} content.bannerSurfaces[${index}]`
    for (const key of ['id', 'placement', 'screen']) {
      if (typeof surface?.[key] !== 'string' || !surface[key].trim()) {
        throw new Error(`${prefix} is missing required string field: ${key}`)
      }
    }
    if (ids.has(surface.id)) throw new Error(`${prefix} has duplicate id: ${surface.id}`)
    if (placements.has(surface.placement)) {
      throw new Error(`${prefix} has duplicate placement: ${surface.placement}`)
    }
    ids.add(surface.id)
    placements.add(surface.placement)
    if (surface.height !== undefined && (!Number.isInteger(surface.height) || surface.height < 1)) {
      throw new Error(`${prefix} height must be a positive integer`)
    }
  }
}

export function demoConfigHash(pack) {
  const publicPack = {
    id: pack.id,
    name: pack.name,
    description: pack.description || '',
    android: pack.android || null,
    ios: pack.ios || null,
    brand: pack.brand,
    content: pack.content,
    launcher: pack.launcher || null,
    web: pack.web || null,
  }
  return createHash('sha256')
    .update(JSON.stringify(publicPack))
    .digest('hex')
    .slice(0, 16)
}

export function demoRuntimeHash(pack) {
  const assetsDir = path.join(pack.directory, 'assets')
  const appSurfaceDir = path.join(pack.directory, 'app-source/web-template/src/screens/local-pack')
  return createHash('sha256')
    .update('braze-demo-runtime/v2\0')
    .update(demoConfigHash(pack))
    .update('\0')
    .update(directoryFingerprint(assetsDir))
    .update('\0')
    .update(directoryFingerprint(appSurfaceDir))
    .digest('hex')
    .slice(0, 24)
}

export function createRuntimeManifest(
  pack,
  { generatedAt = new Date().toISOString(), runtimeHash = demoRuntimeHash(pack) } = {},
) {
  const hash = demoConfigHash(pack)
  return {
    schemaVersion: 2,
    runtimeHashVersion: 2,
    id: pack.id,
    name: pack.name,
    description: pack.description || '',
    externalId: pack.android?.defaultExternalId || pack.brand.demoUser.externalId,
    configHash: hash,
    runtimeHash,
    generatedAt,
    assetBase: `/demo-assets/${pack.id}`,
    sourceMode: pack.web?.distDir ? 'external-web-dist' : 'generated-demo-pack',
    webDistDir: pack.web?.distDir ? packWebDistDir(pack) : '',
    expectedSources: {
      browser: 'http://localhost:5173',
      android: 'file:///android_asset/demo/index.html',
      ios: 'http://localhost:5173',
    },
  }
}

export function generateRuntimeManifest(
  pack,
  { outputPath = generatedRuntimeManifestPath, generatedAt = new Date().toISOString() } = {},
) {
  const runtimeHash = demoRuntimeHash(pack)
  let stableGeneratedAt = generatedAt
  if (fs.existsSync(outputPath)) {
    try {
      const previous = readJson(outputPath)
      if (
        previous.id === pack.id &&
        previous.runtimeHash === runtimeHash &&
        typeof previous.generatedAt === 'string' &&
        previous.generatedAt
      ) {
        stableGeneratedAt = previous.generatedAt
      }
    } catch {
      // Regenerate malformed or legacy runtime manifests.
    }
  }
  const manifest = createRuntimeManifest(pack, { generatedAt: stableGeneratedAt, runtimeHash })
  const changed = writeTextIfChanged(outputPath, `${JSON.stringify(manifest, null, 2)}\n`)
  Object.defineProperty(manifest, 'changed', { value: changed, enumerable: false })
  return manifest
}

